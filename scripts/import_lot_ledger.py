"""Build the lot ledger for Zikim, block 2832 lot 368, from a scrape of the Hof Ashkelon committee's public permit
search (exports/lot_368_zikim/lot_368_all_applications.json, made 25.11.2026).

The ledger is a snapshot of what the committee's register publishes for the lot — not a certified rights ledger.
Each record keeps its source URL and the SHA-256 of the saved detail page. Records are classified by what they do:
  new_dwelling    a new building with its unit numbers (the 300-series two-family houses)
  legalization    "הסדרה בדיעבד" of an existing building — the register's areas are what was legalized, not the house
  addition        a change or addition to an earlier permit (delta semantics)
  infrastructure  development works (permit 20200565: roads, utilities, building plan for 56 units — NOT dwellings)
  public          public buildings (kindergarten, shelter)
Register fields are kept as published; known oddities are flagged, never "fixed":
  total_in_primary  the primary-area field holds the request's total area and the service field is empty
  indirect          found only by the broad search (not the lot search S1a); its page lists lot 368, but it is kept out
                    of the direct-record counts (49 direct + 2 indirect in the 25.11.2026 snapshot)

Usage: python scripts/import_lot_ledger.py <lot_368_all_applications.json> [--dry-run]
"""
from __future__ import annotations

import argparse
import json
import re
import sys
from collections import Counter
from decimal import Decimal
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "knowledge" / "lots" / "hof_ashkelon_2832_368.yaml"
HEADER = ("# Lot ledger — Zikim, block 2832 lot 368 (plan 633-0723718, cell 368). Generated by scripts/import_lot_ledger.py from\n"
          "# the Hof Ashkelon committee's public permit search, snapshot 25.11.2026. A snapshot of the register, not a\n"
          "# certified rights ledger: register areas may be deltas (legalizations, additions) and some fields are misfiled.\n")


def dec(v) -> str | None:
    return None if v is None else str(Decimal(str(v)))


def role(a: dict) -> str:
    text = " ".join(x or "" for x in (a.get("essence"), a.get("description")))
    if re.search(r"פיתוח ותשתיות|עבודות פיתוח", text):
        return "infrastructure"
    if re.search(r"גן ילדים|בית ילדים|פעוטון|מיגון - גן|מבנה ציבור", text):
        return "public"
    if re.search(r"בדיעבד|הסדרת", text):
        return "legalization"
    if a.get("amendment_inferred") or re.search(r"תוספת|שינוי חזית|מהיתר מספר", text):
        return "addition"
    if a.get("housing_unit_numbers") or re.search(r"הקמת (?:בית|מבנה|מגורים)|בית מגורים", text):
        return "new_dwelling"
    return "other"


def building_no(a: dict) -> str | None:
    units = a.get("housing_unit_numbers") or []
    if len(units) >= 2:
        return f"{min(units)}-{max(units)}"
    m = re.search(r"(?:בית|מבנה)\s*(?:מס['׳]?|מספר)?\s*(\d{2,3})\b", a.get("essence") or "")
    return m.group(1) if m else None


PHONE = re.compile(r"(?<!\d)0\d{1,2}-?\d{7}(?!\d)")
FAMILY = re.compile(r"(משפ(?:חת|['׳])\s+|משפ['׳])[א-ת\"'׳״-]+(?:\s+(?:ו?[א-ת\"'׳״-]+)){0,2}")
OWNERS = re.compile(r"(?:(?<!מגרש )\b\d{3}\s*-\s*|\b[A-Z]\s*-\s*)(?=[א-ת])(?!טרם)")   # "312- <names>", "U-<names>": owner list


def redact(text: str) -> str:
    """Keep the register's wording but not personal identifiers: phone numbers, family names and the unit owner lists
    (the source page, linked by source_url and evidence_sha256, keeps the full text)."""
    text = FAMILY.sub(r"\1[שם]", PHONE.sub("[טלפון]", text))
    m = OWNERS.search(text)
    return text[:m.start()].rstrip(" .,-") + " [שמות בעלים הושמטו]" if m else text


def chains(records: list[dict]) -> list[dict]:
    """Buildings whose register areas are deltas: the legalization plus later additions. A building is 'resolved' only
    when every record in its chain has both areas (then the sum is the building's registered area)."""
    out = []
    for b in sorted({r["building"] for r in records if r["building"] and "areas_are_delta" in r["flags"]}, key=lambda x: (len(x), x)):
        recs = [r for r in records if r["building"] == b]
        if len(recs) < 2:
            continue
        known = all(r["primary_m2"] is not None for r in recs)
        out.append({"building": b, "applications": [r["application_id"] for r in recs],
                    "primary_m2": str(sum(Decimal(r["primary_m2"]) for r in recs)) if known else None,
                    "delta_primary_m2": [r["primary_m2"] for r in recs[1:]],
                    "resolved": False,
                    "note_he": "שטחי ההסדרה והתוספות הם תוספות; שטח הבית הכולל אינו מפורסם במאגר — דורש תיק בניין."})
    return out


def build(src: Path) -> dict:
    data = json.loads(src.read_text(encoding="utf-8"))
    apps = [a for a in data["applications"] if a.get("belongs_to_lot_368")]
    records = []
    for a in sorted(apps, key=lambda a: (a.get("submission_date") or "", a["application_id"])):
        r = role(a)
        rec = {
            "application_id": a["application_id"], "type": a.get("application_type"), "status": a.get("status"),
            "role": r, "building": building_no(a), "units": a.get("housing_unit_numbers") or [],
            "primary_m2": dec(a.get("primary_area_m2")), "service_m2": dec(a.get("service_area_m2")),
            "submitted": a.get("submission_date"), "permit_id": a.get("permit_id"),
            "permit_date": a.get("permit_certificate_date"), "essence": redact(a.get("essence") or "")[:200],
            "source_url": a.get("source_url"), "evidence_sha256": a.get("evidence_sha256"), "flags": [],
        }
        m = re.search(r"מהיתר מספר\s*(\d{8})", a.get("essence") or "")
        if m:
            rec["amends"] = m.group(1)       # the permit this one changes (delta on top of it)
            base = next((x for x in records if x["application_id"] == rec["amends"]), None)
            rec["building"] = rec["building"] or (base and base["building"])
        if r == "new_dwelling" and rec["units"] and rec["primary_m2"] and rec["service_m2"] is None:
            rec["flags"].append("total_in_primary")
        if r in ("legalization", "addition"):
            rec["flags"].append("areas_are_delta")
        if r == "infrastructure":
            rec["flags"].append("not_dwellings")
        if "S1a" not in (a.get("found_by_searches") or []):
            rec["flags"].append("indirect")
        records.append(rec)
    direct = [r for r in records if "indirect" not in r["flags"]]
    statuses = Counter(r["status"] for r in direct)
    return {
        "lot": {"locality": "זיקים", "block": "2832", "lot": "368", "plan": "633-0723718", "cell_units_max": 102},
        "snapshot": {"source": data["meta"].get("source"), "generated": data["meta"].get("generated"),
                     "records": len(records), "direct_records": len(direct), "status_counts": dict(statuses),
                     "indirect": [r["application_id"] for r in records if "indirect" in r["flags"]],
                     "note_he": "צילום מצב של מאגר הבקשות הפומבי של הוועדה; אינו ספר זכויות מאושר. שטחי 'הסדרה בדיעבד' ותוספות הם "
                                "תוספות ולא שטח הבית כולו; היתר 20200565 הוא פיתוח ותשתיות ולא יחידות דיור."},
        "delta_chains": chains(records),
        "records": records,
    }


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("src", type=Path)
    ap.add_argument("--dry-run", action="store_true")
    a = ap.parse_args()
    ledger = build(a.src)
    print(f"{ledger['snapshot']['records']} records ({ledger['snapshot']['direct_records']} direct); status {ledger['snapshot']['status_counts']}")
    print("roles", dict(Counter(r["role"] for r in ledger["records"])))
    print("flags", dict(Counter(f for r in ledger["records"] for f in r["flags"])))
    if a.dry_run:
        return
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(HEADER + yaml.safe_dump(ledger, allow_unicode=True, sort_keys=False, width=120), encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT)}")


if __name__ == "__main__":
    sys.exit(main())
