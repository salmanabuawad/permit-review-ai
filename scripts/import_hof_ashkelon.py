"""Import the Hof Ashkelon local committee documents as unverified sources with extracted text.

Input is the folder built on 25.11.2026 from the committee site (hoa.bartech-net.co.il), its plan
archive and gov.il pages, with the manifest.json written while downloading it. Every file is keyed
by its SHA-256: existing entries are never rewritten, and running the import twice changes nothing.

Nothing here is a rule. Every source is FOUND_NOT_READ: downloaded from the official site and
machine-extracted, but not yet read and checked by a person. The extracted text (text layer or OCR)
goes to knowledge/source_texts/hof_ashkelon/<source id>/p001.txt ... for passages and rule
candidates to cite.

Usage:
    python scripts/import_hof_ashkelon.py <folder with manifest.json> [--dry-run] [--no-ocr]
"""
from __future__ import annotations

import argparse
import hashlib
import json
import re
import subprocess
import sys
import tempfile
import zipfile
from concurrent.futures import ThreadPoolExecutor
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[1]
KNOWLEDGE = ROOT / "knowledge"
SOURCES_FILE = KNOWLEDGE / "sources.d" / "hof_ashkelon.yaml"
TEXT_DIR = KNOWLEDGE / "source_texts" / "hof_ashkelon"
JURISDICTION = "hof-ashkelon"
RECEIVED = "2026-11-25"
HEADER = ("# Hof Ashkelon local committee documents — generated by scripts/import_hof_ashkelon.py. Do not edit\n"
          "# by hand; entries are keyed by sha256 and never rewritten. Text is machine-extracted (text layer or\n"
          "# OCR) and unverified: verification stays FOUND_NOT_READ until a reviewer reads the document.\n")

# Some government PDFs use a Hebrew font whose text layer is shifted into U+02A0..U+02BA and reversed.
SHIFTED = re.compile(r"[ʠ-ʺ]+")
MIN_PAGE_CHARS = 40          # below this a PDF page is treated as a scan and OCR'd


def sha256(p: Path) -> str:
    h = hashlib.sha256()
    with p.open("rb") as f:
        for chunk in iter(lambda: f.read(1 << 20), b""):
            h.update(chunk)
    return h.hexdigest()


def fix_shifted(text: str) -> str:
    return SHIFTED.sub(lambda m: "".join(chr(ord(c) + 0x330) for c in m.group(0))[::-1], text)


def pdf_pages(path: Path, ocr: bool) -> tuple[list[str], str]:
    info = subprocess.run(["pdfinfo", str(path)], capture_output=True, text=True).stdout
    n = int(next((l.split()[-1] for l in info.splitlines() if l.startswith("Pages:")), "0"))
    pages, methods = [], set()
    for i in range(1, n + 1):
        t = subprocess.run(["pdftotext", "-layout", "-f", str(i), "-l", str(i), str(path), "-"],
                           capture_output=True, text=True).stdout
        t = fix_shifted(t)
        if len(t.strip()) >= MIN_PAGE_CHARS:
            methods.add("TEXT_LAYER")
        elif ocr:
            with tempfile.TemporaryDirectory() as tmp:
                subprocess.run(["pdftoppm", "-r", "300", "-f", str(i), "-l", str(i), "-gray", "-png",
                                str(path), f"{tmp}/p"], check=True, capture_output=True)
                img = next(Path(tmp).glob("p*.png"))
                t = subprocess.run(["tesseract", str(img), "-", "-l", "heb+eng", "--psm", "4"],
                                   capture_output=True, text=True).stdout
            methods.add("OCR")
        pages.append(t)
    method = "OCR" if methods == {"OCR"} else "MIXED" if len(methods) > 1 else "TEXT_LAYER" if methods else "NONE"
    return pages, method


def office_text(path: Path, members: str) -> list[str]:
    with zipfile.ZipFile(path) as z:
        names = sorted((n for n in z.namelist() if re.fullmatch(members, n)),
                       key=lambda n: int(re.search(r"(\d+)\.xml$", n).group(1)) if re.search(r"\d+\.xml$", n) else 0)
        out = []
        for n in names:
            xml = z.read(n).decode("utf-8", "ignore")
            xml = re.sub(r"</w:p>|</a:p>", "\n", xml)
            out.append(re.sub(r"<[^>]+>", "", xml))
        return out


def extract(path: Path, ocr: bool) -> tuple[list[str], str]:
    ext = path.suffix.lower()
    if ext == ".pdf":
        return pdf_pages(path, ocr)
    if ext == ".docx":
        return office_text(path, r"word/document\.xml"), "TEXT_LAYER"
    if ext in (".pptx", ".ppsx"):
        return office_text(path, r"ppt/slides/slide\d+\.xml"), "TEXT_LAYER"
    return [], "NONE"        # .doc / .rtf: no extractor installed


def classify(group: str, title: str) -> tuple[str, str]:
    """(category, document_type) from the folder the file came from and its title."""
    if group.startswith("תכנית "):
        return "STATUTORY_PLAN", "מסמך תכנית"
    if group.startswith("gov.il"):
        return "GOV_GUIDANCE", "מידע/הנחיות מינהל התכנון"
    if "6/120/03/6" in title or "6-120-03-6" in title:
        return "STATUTORY_PLAN", "מסמך תכנית"
    if re.search(r"^חוק |חוק התכנון", title):
        return "LAW", "חוק"
    if re.search(r"תקנות|תקנון|צו |ספר החוקים|קובץ התקנות", title):
        return "REGULATION", "תקנות"
    if re.search(r"מדיניות", title):
        return "LOCAL_POLICY", "מדיניות ועדה"
    if re.search(r"נוהל|הנחיות|מדריך|עקרונות", title):
        return "LOCAL_POLICY", "נוהל/הנחיות"
    if re.search(r"טופס|^[גדה]-\d|הצהרה|תצהיר|נספח [אבג]|דוגמא|שלט|בקשה ל", title):
        return "LOCAL_POLICY", "טופס"
    if re.search(r"תכנית בינוי|נספח בינוי|תשריט", title):
        return "STATUTORY_PLAN", "תכנית בינוי"
    if re.search(r"שימור|אתרי מורשת", title):
        return "LOCAL_POLICY", "סקר שימור"
    return "LOCAL_POLICY", "מסמך ועדה"


def plan_number(group: str, title: str) -> str | None:
    if group.startswith("תכנית "):
        return group.removeprefix("תכנית ").replace("6-מק-", "6/מק/")
    if "6/120/03/6" in title or "6-120-03-6" in title:
        return "6/120/03/6"
    return None


def build(folder: Path, ocr: bool, skip: set[str] = frozenset()) -> tuple[list[dict], dict[str, list[str]]]:
    """skip: ids already registered — their files are hashed but not re-extracted (OCR is slow)."""
    manifest = json.loads((folder / "manifest.json").read_text(encoding="utf-8"))
    items = [m for m in manifest if m.get("status") == "ok" and m.get("file")]

    def one(m: dict):
        path = folder / m["file"]
        digest = sha256(path)
        sid = f"HA-{digest[:10].upper()}"
        pages, method = ([], "SKIPPED") if sid in skip else extract(path, ocr)
        return m, path, digest, sid, pages, method

    with ThreadPoolExecutor(8) as ex:
        done = list(ex.map(one, items))

    sources, texts, seen = [], {}, set()
    for m, path, digest, sid, pages, method in done:
        if sid in seen:          # the same file published under two names
            continue
        seen.add(sid)
        group = m.get("group", "")
        title = re.sub(r"\s+", " ", m["title"]).strip()
        category, doc_type = classify(group, title)
        texts[sid] = pages
        sources.append({
            "id": sid,
            "category": category,
            "title_he": title,
            "url": m["url"],
            "verification": "FOUND_NOT_READ",
            "jurisdiction": JURISDICTION if not group.startswith("gov.il") else "national",
            "document_type": doc_type,
            "plan_number": plan_number(group, title),
            "file_name": path.name,
            "folder": group,
            "sha256": digest,
            "size_bytes": path.stat().st_size,
            "provenance": {"received": RECEIVED, "official_url": m["url"],
                           "site": "gov.il" if "gov.il" in m["url"] else "hoa.bartech-net.co.il"},
            "text_extraction": method,
            "text_path": f"knowledge/source_texts/hof_ashkelon/{sid}/p*.txt" if any(p.strip() for p in pages) else None,
            "text_pages": len(pages),
            "legal_status_verified": False,
            "notes": None,
        })
    return sorted(sources, key=lambda s: (s["category"], s["title_he"])), texts


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("folder", type=Path)
    ap.add_argument("--dry-run", action="store_true")
    ap.add_argument("--no-ocr", action="store_true")
    a = ap.parse_args()

    existing = {s["id"] for s in (yaml.safe_load(SOURCES_FILE.read_text(encoding="utf-8")) or {}).get("sources", [])} \
        if SOURCES_FILE.exists() else set()
    sources, texts = build(a.folder, ocr=not a.no_ocr, skip=existing)
    new = [s for s in sources if s["id"] not in existing]
    by_cat: dict[str, int] = {}
    for s in new:
        by_cat[s["category"]] = by_cat.get(s["category"], 0) + 1
    print(f"{len(sources)} sources ({len(new)} new); new by category: {by_cat}")
    print("extraction of new:", {m: sum(1 for s in new if s["text_extraction"] == m) for m in ("TEXT_LAYER", "OCR", "MIXED", "NONE")})
    if a.dry_run:
        return
    if new:
        old = (yaml.safe_load(SOURCES_FILE.read_text(encoding="utf-8")) or {}).get("sources", []) if SOURCES_FILE.exists() else []
        SOURCES_FILE.parent.mkdir(parents=True, exist_ok=True)
        body = yaml.safe_dump({"sources": old + new}, allow_unicode=True, sort_keys=False, width=120)
        SOURCES_FILE.write_text(HEADER + body, encoding="utf-8", newline="\n")
    for s in new:
        d = TEXT_DIR / s["id"]
        for i, page in enumerate(texts[s["id"]], 1):
            if page.strip():
                d.mkdir(parents=True, exist_ok=True)
                (d / f"p{i:03d}.txt").write_text(page, encoding="utf-8", newline="\n")
    print(f"wrote {SOURCES_FILE.relative_to(ROOT)} and texts under {TEXT_DIR.relative_to(ROOT)}")


if __name__ == "__main__":
    sys.exit(main())
